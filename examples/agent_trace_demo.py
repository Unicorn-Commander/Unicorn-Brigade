async def example_2_code_edits():
    """
    Example 2: Record code edits (modifications to existing code)

    Use this when an agent modifies existing code rather than creating new code.
    """
    print("\n" + "="*70)
    print("Example 2: Recording Code Edits")
    print("="*70)

    async with async_session() as db_session:
        recorder = AgentTraceRecorder(
            session_id="demo-session-002",
            db_session=db_session,
            user_id="demo-user",
        )

        # Code that was modified by an agent
        modified_code = '''@router.get("/users/{user_id}")
async def get_user(
    user_id: str,
    db: AsyncSession = Depends(get_session),
    current_user: User = Depends(get_current_user)  # Added authentication
):
    """Get user by ID - requires authentication"""
    # Check permissions
    if current_user.id != user_id and not current_user.is_admin:
        raise HTTPException(status_code=403, detail="Permission denied")

    user = await db.get(User, user_id)
    if not user:
        raise HTTPException(status_code=404, detail="User not found")
    return user
'''

        # Record as an edit, not a new generation
        # Note: Using agent_id=None since "code-reviewer" doesn't exist in DB
        contribution = await recorder.record_edit(
            agent_id=None,  # Use None for agents not in the database
            agent_name="Lt. CodeReviewer",
            model="openai/gpt-4o",
            file_path="/app/api/user_routes.py",
            code_content=modified_code,
            prompt="Add authentication and permission checking to the get_user endpoint",
            start_line=42,
            metadata={
                "language": "python",
                "edit_type": "security_enhancement",
                "review_approved": True,
            },
        )

        if contribution:
            print(f"\n✅ Successfully recorded code edit!")
            print(f"   Agent: {contribution.agent_name}")
            print(f"   File: {contribution.location.file_path}")
            print(f"   Change Type: {contribution.change_type.value}")
            print(f"   Edit Type: {contribution.metadata.get('edit_type')}")


