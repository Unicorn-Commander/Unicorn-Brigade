async def example_3_querying_data():
    """
    Example 3: Query attribution data programmatically

    Use the repository to query attributions by agent, file, session, etc.
    """
    print("\n" + "="*70)
    print("Example 3: Querying Attribution Data")
    print("="*70)

    async with async_session() as db_session:
        repo = CodeAttributionRepository(db_session)

        # Query 1: Get recent attributions
        print("\n🔍 Query 1: Get attributions from last 7 days")
        recent = await repo.get_recent(days=7, limit=10)
        print(f"   Found: {len(recent)} attribution(s)")

        for attr in recent[:3]:  # Show first 3
            print(f"   - {attr['filePath']} by {attr['agentName']}")

        # Query 2: Get statistics
        print("\n🔍 Query 2: Get overall statistics")
        stats = await repo.get_stats()
        print(f"   Total attributions: {stats['totalAttributions']}")
        print(f"   Total lines of code: {stats['totalLines']}")
        print(f"   Unique agents: {stats['uniqueAgents']}")
        print(f"   Unique files: {stats['uniqueFiles']}")

        if stats['topAgents']:
            print(f"\n   Top Agents:")
            for agent in stats['topAgents'][:3]:
                print(f"   - {agent['agentName']}: {agent['totalLines']} lines, {agent['attributionCount']} contributions")


