def example_4_api_endpoints():
    """
    Example 4: Query attribution data via REST API

    Use curl or HTTP client to query the Agent Trace API endpoints.
    """
    print("\n" + "="*70)
    print("Example 4: Querying via REST API")
    print("="*70)

    base_url = "http://localhost:8100/api/v1"

    print("\n📡 Available API Endpoints:\n")

    # Query 1: Get file attributions
    print("1️⃣  Get attributions for a specific file:")
    print(f'   curl -X GET "{base_url}/trace/files/app/api/user_routes.py"')

    # Query 2: Get agent attributions
    print("\n2️⃣  Get all code by a specific agent:")
    print(f'   curl -X GET "{base_url}/trace/agents/cpt-fullstack?limit=50"')

    # Query 3: Get session attributions
    print("\n3️⃣  Get all code from a conversation session:")
    print(f'   curl -X GET "{base_url}/trace/sessions/demo-session-001"')

    # Query 4: Get recent activity
    print("\n4️⃣  Get recent attributions (last 7 days):")
    print(f'   curl -X GET "{base_url}/trace/recent?days=7&limit=100"')

    # Query 5: Get statistics
    print("\n5️⃣  Get attribution statistics:")
    print(f'   curl -X GET "{base_url}/trace/stats"')

    # Query 6: Generate report
    print("\n6️⃣  Generate compliance report (CSV):")
    print(f'''   curl -X POST "{base_url}/trace/report" \\
     -H "Content-Type: application/json" \\
     -d '{{"startDate": "2026-01-01", "endDate": "2026-01-31", "format": "csv"}}' \\
     -o code_attribution_report.csv''')

    # Query 7: Health check
    print("\n7️⃣  Check Agent Trace health:")
    print(f'   curl -X GET "{base_url}/trace/health"')


