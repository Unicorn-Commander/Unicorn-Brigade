async def example_1_manual_recording():
    """
    Example 1: Manually record code generation

    Use this when you know exactly what code was generated and where it goes.
    """
    print("\n" + "="*70)
    print("Example 1: Manual Code Generation Recording")
    print("="*70)

    async with async_session() as db_session:
        # Initialize the trace recorder for this session
        recorder = AgentTraceRecorder(
            session_id="demo-session-001",
            db_session=db_session,
            user_id="demo-user",
        )

        # Sample code that was "generated by an agent"
        generated_code = '''@router.get("/users/{user_id}")
async def get_user(
    user_id: str,
    db: AsyncSession = Depends(get_session)
):
    """Get user by ID"""
    user = await db.get(User, user_id)
    if not user:
        raise HTTPException(status_code=404, detail="User not found")
    return user
'''

        # Record the code generation
        contribution = await recorder.record_code_generation(
            agent_id="cpt-fullstack",
            agent_name="Cpt. Fullstack",
            model="anthropic/claude-sonnet-4-5-20250929",
            file_path="/app/api/user_routes.py",
            code_content=generated_code,
            prompt="Create a GET endpoint to retrieve a user by ID with proper error handling",
            start_line=42,  # Where the code starts in the file
            metadata={
                "language": "python",
                "framework": "fastapi",
                "tokens_used": 245,
                "duration_ms": 1850,
            },
        )

        if contribution:
            print(f"\n✅ Successfully recorded code generation!")
            print(f"   Agent: {contribution.agent_name}")
            print(f"   Model: {contribution.model}")
            print(f"   File: {contribution.location.file_path}")
            print(f"   Lines: {contribution.location.start_line}-{contribution.location.end_line}")
            print(f"   Code Hash: {contribution.code_hash}")
            print(f"   Change Type: {contribution.change_type.value}")
        else:
            print("\n❌ Agent Trace is disabled")
            print("   Set AGENT_TRACE_ENABLED=true in .env to enable")


