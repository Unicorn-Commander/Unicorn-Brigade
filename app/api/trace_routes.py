@router.post("/trace/report")
async def generate_report(
    request: ReportRequest,
    session: AsyncSession = Depends(get_session),
    user: AuthUser = Depends(require_api_key),
):
    """
    Generate a compliance report with optional filters.

    Generates a report of code attributions in JSON, CSV, or PDF format.
    Use filters to narrow down results by agent, file, operation type, or date range.

    - **agentId**: Filter by specific agent
    - **filePath**: Filter by file path (partial match)
    - **changeType**: Filter by change type (generation/edit/deletion)
    - **startDate**: Filter by start date (YYYY-MM-DD)
    - **endDate**: Filter by end date (YYYY-MM-DD)
    - **format**: Output format (json/csv/pdf)
    """
    repo = CodeAttributionRepository(session)

    # Parse dates if provided
    start_date = None
    end_date = None
    if request.startDate:
        try:
            start_date = datetime.fromisoformat(request.startDate)
        except ValueError:
            raise HTTPException(status_code=400, detail="Invalid startDate format. Use YYYY-MM-DD")

    if request.endDate:
        try:
            end_date = datetime.fromisoformat(request.endDate)
        except ValueError:
            raise HTTPException(status_code=400, detail="Invalid endDate format. Use YYYY-MM-DD")

    # Search with filters
    attributions = await repo.search(
        agent_id=request.agentId,
        file_path=request.filePath,
        operation=request.changeType,
        start_date=start_date,
        end_date=end_date,
        limit=10000,  # High limit for reports
    )

    if not attributions:
        raise HTTPException(
            status_code=404,
            detail="No attributions found matching the specified filters"
        )

    # Generate report based on format
    if request.format == "json":
        return {
            "reportType": "code_attribution",
            "generatedAt": datetime.utcnow().isoformat() + "Z",
            "filters": request.dict(exclude={"format"}),
            "totalAttributions": len(attributions),
            "attributions": attributions
        }

    elif request.format == "csv":
        # Generate CSV
        output = io.StringIO()
        writer = csv.DictWriter(
            output,
            fieldnames=[
                "id", "sessionId", "agentId", "agentName", "model",
                "filePath", "startLine", "endLine", "changeType", "codeHash", "createdAt"
            ]
        )
        writer.writeheader()
        for attr in attributions:
            writer.writerow({
                "id": attr["id"],
                "sessionId": attr["sessionId"],
                "agentId": attr.get("agentId", ""),
                "agentName": attr["agentName"],
                "model": attr["model"],
                "filePath": attr["filePath"],
                "startLine": attr["startLine"],
                "endLine": attr["endLine"],
                "changeType": attr["changeType"],
                "codeHash": attr["codeHash"],
                "createdAt": attr["createdAt"],
            })

        csv_content = output.getvalue()
        output.close()

        return StreamingResponse(
            iter([csv_content]),
            media_type="text/csv",
            headers={
                "Content-Disposition": f"attachment; filename=code_attribution_report_{datetime.utcnow().strftime('%Y%m%d')}.csv"
            }
        )

    elif request.format == "pdf":
        # PDF generation would require additional dependencies (reportlab, weasyprint, etc.)
        # For now, return a placeholder
        raise HTTPException(
            status_code=501,
            detail="PDF report generation not yet implemented. Use JSON or CSV format."
        )


@router.get("/trace/health")
async def trace_health_check(
    session: AsyncSession = Depends(get_session),
    user: AuthUser = Depends(require_api_key),
):
    """
    Health check for Agent Trace subsystem.

    Returns status and basic statistics about the trace system.
    """
    try:
        repo = CodeAttributionRepository(session)
        stats = await repo.get_stats()

        return {
            "status": "healthy",
            "subsystem": "agent_trace",
            "database": "connected",
            "totalAttributions": stats["totalAttributions"],
            "uniqueAgents": stats["uniqueAgents"],
            "uniqueFiles": stats["uniqueFiles"],
            "timestamp": datetime.utcnow().isoformat() + "Z"
        }
    except Exception as e:
        logger.error(f"Trace health check failed: {e}")
        raise HTTPException(
            status_code=503,
            detail=f"Agent Trace subsystem unhealthy: {str(e)}"
        )
