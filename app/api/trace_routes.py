@router.get("/trace/files/{file_path:path}", response_model=FileAttributionResponse)
async def get_file_attributions(
    file_path: str,
    limit: int = Query(100, ge=1, le=1000),
    offset: int = Query(0, ge=0),
    session: AsyncSession = Depends(get_session),
    user: AuthUser = Depends(require_api_key),
):
    """
    Get all code attributions for a specific file.

    Returns line-by-line attribution information showing which agent generated
    each section of code.

    - **file_path**: Absolute file path (URL-encoded)
    - **limit**: Maximum attributions to return (1-1000)
    - **offset**: Pagination offset
    """
    repo = CodeAttributionRepository(session)

    # Normalize file path (remove leading slash if present)
    normalized_path = file_path.lstrip("/")

    attributions = await repo.get_by_file(normalized_path, limit=limit, offset=offset)

    if not attributions:
        raise HTTPException(
            status_code=404,
            detail=f"No attributions found for file: {normalized_path}"
        )

    # Calculate total lines covered
    total_lines = sum(
        attr["endLine"] - attr["startLine"] + 1
        for attr in attributions
    )

    return {
        "filePath": normalized_path,
        "totalLines": total_lines,
        "attributionCount": len(attributions),
        "attributions": attributions
    }


